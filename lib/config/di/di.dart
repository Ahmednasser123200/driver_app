import 'package:dio/dio.dart';
import 'package:get_it/get_it.dart';
import 'package:injectable/injectable.dart';

import '../../features/order_details/api/client/order_details_api_client.dart';
import '../../features/order_details/api/data_source_impl/remote/order_details_remote_data_source_impl.dart';
import '../../features/order_details/data/datasources/order_details_remote_data_source.dart';
import '../../features/order_details/data/repo/order_details_repo_impl.dart';
import '../../features/order_details/data/services/url_launcher_contact_launcher.dart';
import '../../features/order_details/domain/repo/order_details_repo.dart';
import '../../features/order_details/domain/services/contact_launcher.dart';
import '../../features/order_details/domain/usecases/get_driver_order_details_use_case.dart';
import '../../features/order_details/domain/usecases/update_order_status_use_case.dart';
import '../../features/order_details/presentation/manager/cubit/order_details_cubit.dart';
import 'di.config.dart';

final getIt = GetIt.instance;

@InjectableInit(
  initializerName: 'init',
  preferRelativeImports: true,
  asExtension: true,
)
void configureDependencies() {
  // Register existing dependencies generated by Injectable.
  getIt.init();

  // Order Details API client.
  if (!getIt.isRegistered<OrderDetailsApiClient>()) {
    getIt.registerLazySingleton<OrderDetailsApiClient>(
      () => OrderDetailsApiClient(getIt<Dio>()),
    );
  }

  // Remote data source.
  if (!getIt.isRegistered<OrderDetailsRemoteDataSource>()) {
    getIt.registerFactory<OrderDetailsRemoteDataSource>(
      () => OrderDetailsRemoteDataSourceImpl(getIt<OrderDetailsApiClient>()),
    );
  }

  // Repository.
  if (!getIt.isRegistered<OrderDetailsRepo>()) {
    getIt.registerFactory<OrderDetailsRepo>(
      () => OrderDetailsRepoImpl(getIt<OrderDetailsRemoteDataSource>()),
    );
  }

  // Use cases.
  if (!getIt.isRegistered<GetDriverOrderDetailsUseCase>()) {
    getIt.registerFactory<GetDriverOrderDetailsUseCase>(
      () => GetDriverOrderDetailsUseCase(getIt<OrderDetailsRepo>()),
    );
  }

  if (!getIt.isRegistered<UpdateOrderStatusUseCase>()) {
    getIt.registerFactory<UpdateOrderStatusUseCase>(
      () => UpdateOrderStatusUseCase(getIt<OrderDetailsRepo>()),
    );
  }

  // Contact launcher (dialer / WhatsApp).
  if (!getIt.isRegistered<ContactLauncher>()) {
    getIt.registerFactory<ContactLauncher>(
      () => const UrlLauncherContactLauncher(),
    );
  }

  // Cubit.
  if (!getIt.isRegistered<OrderDetailsCubit>()) {
    getIt.registerFactory<OrderDetailsCubit>(
      () => OrderDetailsCubit(
        getDriverOrderDetailsUseCase: getIt<GetDriverOrderDetailsUseCase>(),
        updateOrderStatusUseCase: getIt<UpdateOrderStatusUseCase>(),
        contactLauncher: getIt<ContactLauncher>(),
      ),
    );
  }
}
